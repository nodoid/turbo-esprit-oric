#!/usr/bin/env python3
"""Generate data/view_data.s: the A-pillar pixels next to the 3D view.

usage: gen_view.py dashboard.scr
dashboard.scr is a 6912-byte Spectrum screen of the game screen right after
the dashboard has been drawn (made with the reference model of the drawing
engine).  Lines 0-95, Spectrum x 228..233 become Oric column 39 of HIRES
lines 4-99 (column 38 is a cyan paper attribute).
"""
import sys


def main():
    scr = open(sys.argv[1], 'rb').read()
    out = ['; generated by tools/gen_view.py - A-pillar column (Oric column 39)',
           '        .export pillar', '        .segment "RODATA"', 'pillar:']
    vals = []
    for y in range(96):
        base = ((y & 0xC0) << 5) + ((y & 7) << 8) + ((y & 0x38) << 2)
        word = (scr[base + 28] << 8) | scr[base + 29]     # x 224..239
        bits = (word >> (16 - 4 - 6)) & 0x3F               # x 228..233
        vals.append(0xC0 | bits)
    for i in range(0, 96, 16):
        out.append('        .byte ' + ','.join('$%02X' % v for v in vals[i:i + 16]))
    open('data/view_data.s', 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
