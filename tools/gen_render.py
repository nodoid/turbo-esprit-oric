#!/usr/bin/env python3
"""Generate data/render_data.inc: lookup tables for src/render.s.

The far perspective table D78FE (59 records of 12 bytes, static) is read
from data/zxram.bin (the original's working RAM image, $5B00-$7BBD).

  PSc[k]   (c = 7..11, k = 0..58): sum of field c of records 0..k-1, mod 256.
           A line stepper call over records k..k2-1 then needs
           PSc[k2] - PSc[k] pixels (the original's 82BC loop).
  IY0[k]:  field 0 (ground line y1) of record k.
"""
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
ZX_LO = 0x5B00
TABLE = 0x78FE
NREC = 59           # record 58 is the horizon (field 7 = $80)


def main():
    ram = open(os.path.join(ROOT, 'data', 'zxram.bin'), 'rb').read()

    def rec(k, f):
        return ram[TABLE + 12 * k + f - ZX_LO]
    # render.s relies on: only record 58 is the horizon (field 7 bit 7), and
    # every line record (D76AC..D770B) starts with acc < d (y-major) or < e.
    assert rec(58, 7) == 0x80 and all(rec(k, 7) < 0x80 for k in range(58))
    for r in range(6):
        a = 0x76AC + 16 * r - ZX_LO
        acc, e, d = ram[a + 11], ram[a + 12], ram[a + 13]
        assert acc < (d if d >= e else e), hex(a)
    out = ['; generated by tools/gen_render.py from data/zxram.bin - do not edit', '']

    def table(name, vals):
        out.append(name + ':')
        for i in range(0, len(vals), 16):
            out.append('        .byte ' + ','.join('$%02X' % v for v in vals[i:i + 16]))
    for c in range(7, 12):
        s, vals = 0, []
        for k in range(NREC):
            vals.append(s)
            if k < 58:
                s = (s + rec(k, c)) & 0xFF
        table('PS%d' % c, vals)
    table('IY0', [rec(k, 0) for k in range(NREC)])
    path = os.path.join(ROOT, 'data', 'render_data.inc')
    open(path, 'w').write('\n'.join(out) + '\n')
    print('wrote', path)


if __name__ == '__main__':
    sys.exit(main())
