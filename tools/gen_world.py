#!/usr/bin/env python3
"""Generate data/world_tables.inc (included by src/world.s) from the original
tape: the road-description tables of S958B.

  T_980E  4 words   street-class record pointers (identity addresses $7539..)
  T_9816  4 x 16    per-heading building table {stride, (dL,dH), destA, destB,
                    (dL,dH), destA, destB, pad} - kept in the original layout;
                    every dest lies in page $78 (checked), src/world.s only
                    uses their low bytes.
  T_9854  128       junction-variant nibbles
  T_98D4  32        variant -> (D75E7, D75EC)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import zxtape  # noqa: E402

ROOT = os.path.join(HERE, '..')


def rows(data, n=16):
    for i in range(0, len(data), n):
        yield '        .byte ' + ','.join('$%02X' % b for b in data[i:i + n])


def main():
    img = zxtape.load_image(os.path.join(ROOT, 'orig', 'TurboEsprit.tzx'))
    out = ['; generated by tools/gen_world.py from orig/TurboEsprit.tzx - do not edit', '']
    t980e = img[0x980E:0x9816]
    out.append('T_980E:')
    out.append('        .word ' + ','.join('$%04X' % (t980e[i] | t980e[i + 1] << 8) for i in range(0, 8, 2)))
    t9816 = img[0x9816:0x9816 + 64]
    for h in range(4):
        r = t9816[16 * h:16 * h + 16]
        for o in (4, 6, 10, 12):
            assert r[o + 1] == 0x78, 'dest not in page $78'
    out.append('T_9816:')
    out.extend(rows(t9816))
    out.append('T_9854:')
    out.extend(rows(img[0x9854:0x98D4]))
    out.append('T_98D4:')
    out.extend(rows(img[0x98D4:0x98F4]))
    with open(os.path.join(ROOT, 'data', 'world_tables.inc'), 'w') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote data/world_tables.inc')


if __name__ == '__main__':
    main()
